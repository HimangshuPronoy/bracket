interface I18nContextType {
  language: string;
  setLanguage: (lang: string) => void;
  autoDetect: boolean;
  setAutoDetect: (auto: boolean) => void;
  t: (key: string, fallback?: string) => string;
  languages: Language[];
}

const I18nContext = createContext<I18nContextType>({
  language: 'en',
  setLanguage: () => {},
  autoDetect: false,
  setAutoDetect: () => {},
  t: (key: string, fallback?: string) => fallback || key,
  languages: SUPPORTED_LANGUAGES,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState('en');
  const [autoDetect, setAutoDetectState] = useState(false);

  useEffect(() => {
    if (typeof window === 'undefined') return;

    const storedAuto = localStorage.getItem('bracket_autodetect');
    const isAuto = storedAuto === 'true';
    setAutoDetectState(isAuto);

    const storedLang = localStorage.getItem('bracket_lang');

    if (storedLang && translations[storedLang]) {
      setLanguageState(storedLang);
    } else if (isAuto) {
      const browserLang = (navigator.language || 'en').split('-')[0].toLowerCase();
      if (translations[browserLang]) {
        setLanguageState(browserLang);
      } else {
        setLanguageState('en');
      }
    } else {
      setLanguageState('en');
    }
  }, []);

  const setLanguage = (newLang: string) => {
    if (!translations[newLang]) return;
    setLanguageState(newLang);
    if (typeof window !== 'undefined') {
      localStorage.setItem('bracket_lang', newLang);
      // If user explicitly picks a language, we remember their manual choice
      localStorage.setItem('bracket_autodetect', 'false');
      setAutoDetectState(false);
    }
  };

  const setAutoDetect = (val: boolean) => {
    setAutoDetectState(val);
    if (typeof window !== 'undefined') {
      localStorage.setItem('bracket_autodetect', String(val));
      if (val) {
        const browserLang = (navigator.language || 'en').split('-')[0].toLowerCase();
        if (translations[browserLang]) {
          setLanguageState(browserLang);
          localStorage.setItem('bracket_lang', browserLang);
        }
      }
    }
  };

  const t = (key: string, fallback?: string): string => {
    const parts = key.split('.');
    const currentDict = translations[language] || translations.en;

    let result: any = currentDict;
    for (const part of parts) {
      if (result && typeof result === 'object' && part in result) {
        result = result[part];
      } else {
        result = undefined;
        break;
      }
    }

    if (typeof result === 'string') return result;

    // Fallback to English
    let fallbackResult: any = translations.en;
    for (const part of parts) {
      if (fallbackResult && typeof fallbackResult === 'object' && part in fallbackResult) {
        fallbackResult = fallbackResult[part];
      } else {
        fallbackResult = undefined;
        break;
      }
    }

    if (typeof fallbackResult === 'string') return fallbackResult;

    return fallback || key;
  };

  return (
    <I18nContext.Provider
      value={{
        language,
        setLanguage,
        autoDetect,
        setAutoDetect,
        t,
        languages: SUPPORTED_LANGUAGES,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
